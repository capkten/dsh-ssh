/** Extracted DSH 0.2.1-rc.2 app tree (read-only source of the stock preset row). */
const EXTRACT_ROOT = process.env.DSH_EXTRACT_ROOT ?? ''
const STANDARD_PRESET_PATCH = join(EXTRACT_ROOT, 'dsh', 'node_modules', '@deepseek-ai', 'dsh-web-app', 'presets', 'standard.patch.yml')

const ALL_STAGES = [
  'local-hostname',
  'remote-shell',
  'remote-read',
  'remote-glob-grep',
  'remote-write',
  'remote-delete',
  'ssh-down',
  'concurrency',
  'local-unaffected',
]

function parseStages() {
  const arg = process.argv.find(value => value.startsWith('--stages='))
  if (arg === undefined) return ALL_STAGES
  const requested = arg.slice('--stages='.length).split(',').map(value => value.trim()).filter(Boolean)
  const unknown = requested.filter(stage => !ALL_STAGES.includes(stage))
  if (unknown.length > 0) throw new Error(`unknown stages: ${unknown.join(', ')}; known: ${ALL_STAGES.join(', ')}`)
  return requested
}

/** Profile bundles for the local control run (no dsh-ssh). */
const LOCAL_BUNDLES = ['@deepseek-ai/dsh-base', '@deepseek-ai/dsh-headless']

/** Profile bundles for the remote run (dsh-ssh mounted over headless). */
const REMOTE_BUNDLES = [...LOCAL_BUNDLES, 'dsh-ssh']

/** Profile patch shared by every stage: keep auxiliary LLM callers off the mock script. */
function quietLlmPatch() {
  return `# generated by tests/integration/run-e2e.mjs 鈥?auxiliary LLM callers off the mock script
- id: session-title-llm
  disabled: true
`
}

/**
 * Build the isolated remote profile patch for the CURRENT architecture:
 *  - the host composition mounts the connection registry and the agent-preset
 *    registry (the headless bundle has neither);
 *  - `dsh-ssh` (aggregate) now only registers the per-connection remote presets,
 *    so the profile must NOT disable the local subprocess/fs providers;
 *  - the web-only rows are disabled because headless has no `connection` service.
 */
function remotePatch(extraInserts = '') {
  return `# generated by tests/integration/run-e2e.mjs - isolated test profile (preset architecture)
- id: session-title-llm
  disabled: true
- insert:
    - id: ssh-registry
      name: dsh-ssh/registry
    - id: agent-presets
      name: '@deepseek-ai/dsh-agent-preset-registry'
      config:
        default: standard
${extraInserts}- id: ssh-remote
  name: dsh-ssh
  config: {}
- id: directory-picker-ssh
  disabled: true
- id: ssh-web-channel
  disabled: true
`
}

/**
 * Copy the stock `standard` preset declaration out of the extracted app next to
 * the isolated profile and return the `--patch` path that mounts it. The
 * headless bundle does not ship the preset roster (only the Web app does).
 */
function mountStandardPreset(profileDir) {
  const patchPath = join(profileDir, 'standard.preset.patch.yml')
  writeFileSync(patchPath, readFileSync(STANDARD_PRESET_PATCH, 'utf8'))
  return patchPath
}

/**
 * Seed the connection registry and the local placeholder tree for one remote
 * route, then return the placeholder directory to use as the CLI process cwd.
 * A headless session created from that cwd carries the placeholder in its
 * session header, which is exactly what the preset controller routes on.
 */
function seedRemoteRoute(home, target, remoteCwd, scratch) {
  const connectionId = 'c1'
  const stateFile = join(home, 'dsh-ssh-connections.json')
  writeFileSync(stateFile, `${JSON.stringify({
    connections: [{
      id: connectionId,
      label: `e2e ${target.user}@${target.host}`,
      host: target.host,
      port: Number(target.port),
      username: target.user,
      privateKeyPath: target.key,
      cwd: remoteCwd,
    }],
  }, undefined, 2)}\n`)
  const segments = scratch.split('/').filter(segment => segment !== '')
  const placeholder = join(home, 'dsh-ssh-routes', connectionId, ...segments)
  mkdirSync(placeholder, { recursive: true })
  return { connectionId, stateFile, placeholder }
}

/** Install dsh-ssh + the preset registry into one isolated remote profile. */
function prepareRemoteProfile(home, profileName, target, scratch) {
  const dir = join(home, 'profiles', profileName)
  mkdirSync(dir, { recursive: true })
  const probeLog = join(dir, 'e2e-probe.log')
  const probeFile = join(dir, 'e2e-probe.mjs')
  writeFileSync(probeFile, `import { appendFileSync } from 'node:fs'
const OUT = ${JSON.stringify(probeLog)}
function log(value) {
  try { appendFileSync(OUT, JSON.stringify(value) + '\\n') } catch {}
}
export function apply(ctx) {
  log({ event: 'probe-mounted' })
  ctx.on('agent/created', ({ agent, source }) => {
    log({ event: 'agent/created', source, id: agent?.id, cwd: agent?.session?.header?.cwd })
  })
  ctx.on('agent-preset/selected', (...args) => log({ event: 'agent-preset/selected', args }))
  ctx.inject(['sshRegistry'], (child) => {
    try {
      log({ event: 'ssh-registry', connections: child.sshRegistry.list() })
    } catch (error) {
      log({ event: 'ssh-registry-error', message: String(error) })
    }
    child.on('agent/created', ({ agent }) => {
      log({ event: 'agent/created-inject', id: agent?.id, cwd: agent?.session?.header?.cwd })
    })
  })
}
`)
  const probeInsert = `    - id: e2e-probe
      name: ./e2e-probe.mjs
`
  writeProfile({ home, name: profileName, bundles: REMOTE_BUNDLES, patchYaml: remotePatch(probeInsert) })
  installLocalDshSsh(dir, REMOTE_PROFILE_PACKAGES)
  const presetPatch = mountStandardPreset(dir)
  const route = seedRemoteRoute(home, target, target.cwd ?? '/home/test', scratch)
  return { dir, presetPatch, probeLog, ...route }
}

/** Read the test-only probe log (diagnostics for preset routing). */
function readProbeLog(path) {
  try {
    return readFileSync(path, 'utf8').slice(0, 4000)
  } catch {
    return '<no probe log>'
  }
}

/** A run result shaped for the report table. */
function result(id, requirement, status, detail, evidence) {
  return { id, requirement, status, detail, evidence }
}

function assertRunHealthy(run) {
  const problems = []
  const cleanExit = run.exitCode === 0 || (run.terminatedAfterFinal === true && run.finalText.trim() !== '')
  if (!cleanExit) problems.push(`headless exit ${run.exitCode}: ${(run.stderr || run.stdout).slice(0, 1500)}`)
  if (run.finalText.trim() === '') problems.push('no final text event')
  return problems
}

function toolOutput(run) {
  return run.toolResults.map(entry => String(entry.result ?? '')).join('\n')
}

function toolStatus(run) {
  return run.toolResults.map(entry => entry.status)
}

async function withHome(label, action) {
  const home = makeIsolatedHome(label)
  try {
    return await action(home)
  } finally {
    destroyHome(home)
  }
}

async function withMock(options, action) {
  const mock = await startMockLlm(options)
  try {
    return await action(mock)
  } finally {
    await mock.close()
  }
}

function remoteFixture(target, scratch) {
  const command = [
    `mkdir -p '${scratch}/git'`,
    `printf 'remote fixture line\\n' > '${scratch}/fixture.txt'`,
    `printf 'nested needle line\\n' > '${scratch}/nested.txt'`,
    `cd '${scratch}/git'`,
    `git init -q .`,
    `printf 'tracked\\n' > tracked.txt`,
    `git add tracked.txt`,
    `git -c user.email=test@example.invalid -c user.name='dsh test' commit -qm init`,
    `git rev-parse --short HEAD > '${scratch}/git-head.txt'`,
    `echo FIXTURE_OK`,
  ].join(' && ')
  const outcome = sshExec(target, command)
  if (outcome.status !== 0) throw new Error(`remote fixture setup failed: ${outcome.stderr}`)
}

/* ------------------------------------------------------------------ stages */

async function stageLocalHostname() {
  return withHome('dsh-ssh-e2e-local', async (home) => {
    writeProfile({ home, name: 'local', bundles: LOCAL_BUNDLES, patchYaml: quietLlmPatch() })
    return await withMock({
      sequence: ['tool_call_success', 'success'],
      toolName: 'pwsh',
      toolArguments: JSON.stringify({ description: 'Print local host', command: 'hostname; (Get-Location).Path' }),
      successText: 'local stage done',
    }, async (mock) => {
      const run = await runHeadless({ home, profile: 'local', llmBaseURL: mock.baseURL, task: 'report the local host' })
      const problems = assertRunHealthy(run)
      const output = toolOutput(run)
      if (!output.toLowerCase().includes(localHostname().toLowerCase())) problems.push(`tool output does not contain local hostname ${localHostname()}: ${output.slice(0, 300)}`)
      if (run.toolCalls[0]?.tool !== 'pwsh') problems.push(`unexpected tool ${JSON.stringify(run.toolCalls[0]?.tool)}`)
      return result('local-hostname', '1', problems.length === 0 ? 'pass' : 'fail',
        problems.length === 0 ? 'headless local session reports the Windows host' : problems.join('; '),
        { command: run.command, exitCode: run.exitCode, tool: run.toolCalls[0]?.tool, output: output.slice(0, 500) })
    })
  })
}

async function stageRemoteShell() {
  return withHome('dsh-ssh-e2e-remote', async (home) => {
    const scratch = createRemoteScratch(SSH)
    try {
      remoteFixture(SSH, scratch)
      if (process.env.DSH_E2E_READONLY_SCRATCH === '1') sshExec(SSH, `chmod 555 '${scratch}'`)
      const fixtureProbe = sshExec(SSH, `ls -ld '${scratch}' && ls '${scratch}'`).stdout
      const { placeholder, presetPatch, probeLog } = prepareRemoteProfile(home, 'remote', SSH, scratch)
      return await withMock({
        sequence: process.env.DSH_E2E_NO_TOOL === '1' ? ['success'] : ['tool_call_success', 'success'],
        toolName: process.env.DSH_E2E_TOOL ?? 'bash',
        toolArguments: JSON.stringify({
          ...(process.env.DSH_E2E_WORKDIR === undefined ? {} : { workdir: process.env.DSH_E2E_WORKDIR }),
          description: 'Report remote host identity',
          command: `hostname; pwd; uname -s; id -un; ls -ld '${scratch}'; cd '${scratch}/git' && git rev-parse --short HEAD && git ls-files`,
        }),
        successText: 'remote shell done',
      }, async (mock) => {
        const run = await runHeadless({
          home, profile: 'remote', llmBaseURL: mock.baseURL, task: 'report the remote host identity',
          cwd: placeholder, extraArgs: ['--patch', presetPatch],
          timeoutMs: Number(process.env.DSH_E2E_RUN_TIMEOUT_MS ?? 120_000),
        })
        const problems = assertRunHealthy(run)
        const output = toolOutput(run)
        const scratchProbe = sshExec(SSH, `test -d '${scratch}' && echo YES || echo NO`).stdout.trim()
        if (scratchProbe !== 'YES') problems.push(`remote scratch tree is missing after the run: ${scratch}`)
        const expectedHost = process.env.DSH_E2E_EXPECT_HOSTNAME ?? ''
        if (toolStatus(run)[0] !== 'completed') problems.push(`bash tool status ${JSON.stringify(toolStatus(run))}`)
        if (!/Linux/u.test(output)) problems.push(`no Linux uname in tool output: ${output.slice(0, 300)}`)
        if (!output.includes(scratch)) problems.push(`remote pwd is not the placeholder's remote path: ${output.slice(0, 400)}`)
        if (expectedHost !== '' && !output.includes(expectedHost)) problems.push(`expected host ${expectedHost} missing: ${output.slice(0, 300)}`)
        if (!/tracked\.txt/u.test(output)) problems.push(`remote git did not list the tracked fixture: ${output.slice(0, 400)}`)
        if (output.toLowerCase().includes(localHostname().toLowerCase())) problems.push('tool output leaked the local Windows hostname (remote routing fell back locally)')
        const sessionCwd = run.events.find(event => event.type === 'session')?.cwd ?? ''
        if (!sessionCwd.includes('dsh-ssh-test-')) problems.push(`session cwd is not the remote scratch tree: ${sessionCwd}`)
        return result('remote-shell', '2, 8', problems.length === 0 ? 'pass' : 'fail',
          problems.length === 0 ? 'remote bash ran in the placeholder cwd on the Linux target; git works there' : problems.join('; '),
          {
            command: run.command, exitCode: run.exitCode, terminatedAfterFinal: run.terminatedAfterFinal,
            sessionCwd, scratchProbe, output: output.slice(0, 700), probe: readProbeLog(probeLog),
          })
      })
    } finally {
      removeRemoteScratch(SSH, scratch)
    }
  })
}

async function stageRemoteRead() {
  return withHome('dsh-ssh-e2e-read', async (home) => {
    const scratch = createRemoteScratch(SSH)
    try {
      remoteFixture(SSH, scratch)
      const { placeholder, presetPatch, probeLog } = prepareRemoteProfile(home, 'remote', SSH, scratch)
      const readOne = async (path, marker) => withMock({
        sequence: ['tool_call_success', 'success'],
        toolName: 'read',
        toolArguments: JSON.stringify({ file_path: path }),
        successText: 'read done',
      }, async (mock) => {
        const run = await runHeadless({
          home, profile: 'remote', llmBaseURL: mock.baseURL, task: 'read the fixture',
          cwd: placeholder, extraArgs: ['--patch', presetPatch],
        })
        const output = toolOutput(run)
        return { run, output, ok: run.exitCode === 0 && toolStatus(run)[0] === 'completed' && output.includes(marker) }
      })
      const file = await readOne(`${scratch}/fixture.txt`, 'remote fixture line')
      if (!file.ok) {
        return result('remote-read', '3', 'fail', 'native read did not return the remote fixture content', { output: file.output.slice(0, 500), stderr: file.run.stderr.slice(0, 500) })
      }
      const git = await readOne(`${scratch}/git/.git/HEAD`, 'ref: refs/heads/')
      return result('remote-read', '3', git.ok ? 'pass' : 'fail',
        git.ok ? 'native read sees remote files and remote .git through the SSH filesystem' : 'remote file read worked but .git/HEAD read failed',
        { file: file.output.slice(0, 300), gitHead: git.output.slice(0, 300) })
    } finally {
      removeRemoteScratch(SSH, scratch)
    }
  })
}

async function stageRemoteGlobGrep() {
  return withHome('dsh-ssh-e2e-search', async (home) => {
    const scratch = createRemoteScratch(SSH)
    try {
      remoteFixture(SSH, scratch)
      const { placeholder, presetPatch, probeLog } = prepareRemoteProfile(home, 'remote', SSH, scratch)
      const globRun = await withMock({
        sequence: ['tool_call_success', 'success'],
        toolName: 'glob',
        toolArguments: JSON.stringify({ pattern: '**/*.txt', path: scratch }),
        successText: 'glob done',
      }, async (mock) => runHeadless({
        home, profile: 'remote', llmBaseURL: mock.baseURL, task: 'find the text files',
        cwd: placeholder, extraArgs: ['--patch', presetPatch],
      }))
      const globOutput = toolOutput(globRun)
      const globOk = globRun.exitCode === 0 && toolStatus(globRun)[0] === 'completed' && globOutput.includes('fixture.txt')
      const grepRun = await withMock({
        sequence: ['tool_call_success', 'success'],
        toolName: 'grep',
        toolArguments: JSON.stringify({ pattern: 'needle', path: scratch }),
        successText: 'grep done',
      }, async (mock) => runHeadless({
        home, profile: 'remote', llmBaseURL: mock.baseURL, task: 'search the fixture',
        cwd: placeholder, extraArgs: ['--patch', presetPatch],
      }))
      const grepOutput = toolOutput(grepRun)
      const grepOk = grepRun.exitCode === 0 && toolStatus(grepRun)[0] === 'completed' && grepOutput.includes('nested.txt')
      const problems = []
      if (!globOk) problems.push(`glob failed (${JSON.stringify(toolStatus(globRun))}): ${globOutput.slice(0, 400)}`)
      if (!grepOk) problems.push(`grep failed (${JSON.stringify(toolStatus(grepRun))}): ${grepOutput.slice(0, 400)}`)
      return result('remote-glob-grep', '3', problems.length === 0 ? 'pass' : 'fail',
        problems.length === 0
          ? 'the remote-preset glob/grep tools (remote find/grep over SSH subprocess) found the remote files'
          : problems.join('; '),
        { glob: globOutput.slice(0, 400), grep: grepOutput.slice(0, 400) })
    } finally {
      removeRemoteScratch(SSH, scratch)
    }
  })
}

