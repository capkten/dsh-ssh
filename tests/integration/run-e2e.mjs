const STAGE_IMPL = {
  'local-hostname': stageLocalHostname,
  'remote-shell': stageRemoteShell,
  'remote-read': stageRemoteRead,
  'remote-glob-grep': stageRemoteGlobGrep,
  'remote-write': stageRemoteWrite,
  'remote-delete': stageRemoteDelete,
  'ssh-down': stageSshDown,
  'concurrency': stageConcurrency,
  'local-unaffected': stageLocalUnaffected,
}

async function main() {
  assertPrerequisites()
  const stages = parseStages()
  console.log(`dsh-ssh integration driver`)
  console.log(`repo:     ${process.cwd()}`)
  console.log(`local:    ${localHostname()}`)
  console.log(`remote:   ${SSH.user}@${SSH.host}:${SSH.port}  (2nd: ${SSH2.user}@${SSH2.host})`)
  console.log(`stages:   ${stages.join(', ')}\n`)

  const results = []
  for (const id of stages) {
    const started = Date.now()
    process.stdout.write(`[stage] ${id} ... `)
    try {
      const outcome = await STAGE_IMPL[id]()
      outcome.elapsedMs = Date.now() - started
      results.push(outcome)
      console.log(`${outcome.status.toUpperCase()}${outcome.status === 'pass' ? '' : ` 閳?${outcome.detail}`}`)
    } catch (error) {
      const outcome = result(id, '?', 'fail', error instanceof Error ? error.message : String(error), {})
      outcome.elapsedMs = Date.now() - started
      results.push(outcome)
      console.log(`FAIL 閳?${outcome.detail}`)
    }
  }

  const reportPath = join(tmpdir(), `dsh-ssh-e2e-report-${Date.now()}.json`)
  writeFileSync(reportPath, `${JSON.stringify({ ranAt: new Date().toISOString(), localHostname: localHostname(), ssh: SSH, results }, undefined, 2)}\n`)

  console.log('\n=== acceptance summary ===')
  for (const outcome of results) {
    console.log(`${outcome.status.padEnd(10)} req ${String(outcome.requirement).padEnd(8)} ${outcome.id.padEnd(18)} ${outcome.detail}`)
  }
  console.log(`\nreport: ${reportPath}`)
  const failed = results.filter(outcome => outcome.status === 'fail')
  const gaps = results.filter(outcome => outcome.status === 'known-gap')
  if (gaps.length > 0) console.log(`known gaps not counted as failures: ${gaps.map(outcome => outcome.id).join(', ')}`)
  if (failed.length > 0) {
    console.error(`FAILED stages: ${failed.map(outcome => outcome.id).join(', ')}`)
    process.exitCode = 1
  } else {
    console.log('ALL REQUESTED STAGES PASSED (or were documented known gaps)')
  }
}

main().catch((error) => {
  console.error(error instanceof Error ? error.stack ?? error.message : String(error))
  process.exitCode = 1
})
