#!/usr/bin/env node
/**
 * dsh-ssh end-to-end acceptance driver (isolated; safe to run next to the real
 * Desktop app).
 *
 * Every stage:
 *  - uses a throwaway `$DSH_HOME` under %TEMP% and a throwaway profile;
 *  - drives the REAL harness (`bin.js --profile <test> --json`) through a
 *    scripted Messages mock server, so the real agent loop calls the real
 *    model-facing tools with no provider key and no network model calls;
 *  - writes only inside a fresh `/tmp/dsh-ssh-test-*` tree on the remote host
 *    and removes it afterwards.
 *
 * Stages map to the user acceptance list:
 *  local-hostname    1  local tools report the Windows host
 *  remote-shell      2  remote bash reports remote hostname/pwd/uname + git
 *  remote-read       3  native read sees a remote file and remote .git (read half)
 *  remote-glob-grep  3  native glob/grep over SSH (known gap: packaged rg path)
 *  remote-write      4  native write really mutates the remote temp tree
 *  remote-delete     4  native bash deletes it again (real remote change)
 *  ssh-down          5  an unreachable SSH target fails closed (no local fallback)
 *  concurrency       6  two isolated remote sessions on two hosts do not cross
 *  local-unaffected  7  the local profile keeps working after remote stages
 *  (8) git through remote bash is covered by remote-shell; background jobs and
 *      the PTY terminal are NOT mounted by the headless bundle 閳?see README.
 *
 * Run from the repo root:
 *   node tests/integration/run-e2e.mjs
 *   node tests/integration/run-e2e.mjs --stages local-hostname,ssh-down
 *
 * Prerequisites:
 *   - `npm run build` in the repo (lib/ exists) for every *remote* stage;
 *   - tests/_deps installed (see tests/integration/README.md);
 *   - SSH key auth to the targets (see ssh-preflight.mjs).
 *
 * Env: DSH_SSH_HOST/USER/PORT/KEY, DSH_SSH_HOST2/USER2, DSH_E2E_KEEP=1 to keep
 * the isolated homes, DSH_E2E_EXPECT_HOSTNAME to pin the expected remote host.
 */

